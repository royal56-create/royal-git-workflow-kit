"""Safe .gitignore template generation."""

from __future__ import annotations

from pathlib import Path

RULES = {
    "python": ["__pycache__/", "*.py[cod]", ".venv/", "venv/", ".pytest_cache/", ".coverage", "dist/", "build/", "*.egg-info/"],
    "node": ["node_modules/", "dist/", "coverage/", ".npm/", ".env", ".env.*"],
    "java": ["*.class", "*.jar", "target/", ".gradle/", "build/"],
    "c": ["*.o", "*.obj", "*.exe", "*.out", "build/", "cmake-build-*/"],
    "cpp": ["*.o", "*.obj", "*.exe", "*.out", "build/", "cmake-build-*/"],
    "vscode": [".vscode/*", "!.vscode/extensions.json", "!.vscode/settings.json"],
    "jetbrains": [".idea/", "*.iml"],
    "macos": [".DS_Store", ".AppleDouble", ".LSOverride"],
    "windows": ["Thumbs.db", "Desktop.ini", "$RECYCLE.BIN/"],
}


def generate_gitignore(stacks: list[str]) -> str:
    normalized = [item.lower() for item in stacks]
    unknown = sorted(set(normalized) - RULES.keys())
    if unknown:
        raise ValueError(f"Unknown stack(s): {', '.join(unknown)}. Available: {', '.join(sorted(RULES))}")
    lines = ["# Generated by Royal Git Workflow Kit", ""]
    for stack in dict.fromkeys(normalized):
        lines.extend([f"# {stack}", *RULES[stack], ""])
    return "\n".join(lines).rstrip() + "\n"


def write_gitignore(content: str, destination: str | Path = ".gitignore") -> Path:
    target = Path(destination)
    if target.exists():
        raise FileExistsError(f"{target} already exists; refusing to overwrite it")
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    return target
